"""Build step: pack the files listed in resources.FILES into a generated
module, _bundle.py.

PyInstaller compiles that module into the exe, which is how the web UI, the
config template and the font table travel inside CXHelper.exe instead of
sitting next to it as files. The UI's JS and CSS are minified on the way in
(comments and whitespace stripped) with rjsmin / rcssmin.

Called by build_release.py, which writes the module into gui/build/stage/;
_bundle.py is a build artifact and is not used when the app runs from source.
"""
import base64
import io
import json
import os
import sys
import zipfile

import resources

HERE = os.path.dirname(os.path.abspath(__file__))
LINE = 100


def minified(name, data):
    if name.endswith(".js"):
        import rjsmin
        return rjsmin.jsmin(data.decode("utf-8")).encode("utf-8")
    if name.endswith(".css"):
        import rcssmin
        return rcssmin.cssmin(data.decode("utf-8")).encode("utf-8")
    if name.endswith(".json"):
        return json.dumps(json.loads(data), ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    return data


def build(out, extra=None):
    """Write the bundle module to `out`. `extra` maps further archive names to
    bytes (build metadata such as the selftest reference values)."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for name in resources.FILES:
            raw = resources.read(name)
            packed = minified(name, raw)
            z.writestr(name, packed)
            print("  %-32s %8d -> %8d bytes" % (name, len(raw), len(packed)))
        for name, data in (extra or {}).items():
            z.writestr(name, data)
            print("  %-32s %8d bytes" % (name, len(data)))
    resources.ui_html()  # fails here, not at the user's first launch, if index.html changed shape

    encoded = base64.b64encode(buf.getvalue()).decode("ascii")
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write("# Generated by build_bundle.py - do not edit.\nARCHIVE = (\n")
        for i in range(0, len(encoded), LINE):
            f.write('    "%s"\n' % encoded[i:i + LINE])
        f.write(")\n")
    print("  wrote %s (%d KB)" % (out, os.path.getsize(out) // 1024))


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "_bundle.py"))
